// One-time/occasional generator, not run at build/runtime. Produces
// lib/country-data.ts: a small, static, client-bundle-friendly list of
// {code, name, flag, dialCode, currency} — derived by joining
// world-countries (name/flag/currency) with libphonenumber-js's own
// supported-country + calling-code list (the actual source of truth for
// what a phone-number picker should offer, since it's the same library
// doing the validation). world-countries itself is a devDependency only
// (~1-2MB of metadata we don't want in the client bundle) — this script
// reads it once and writes out only the ~5 fields per country we need.
import countries from "world-countries";
import { getCountries, getCountryCallingCode } from "libphonenumber-js";
import { writeFileSync } from "fs";

const byCca2 = new Map(countries.map((c) => [c.cca2, c]));

const rows = getCountries()
  .map((code) => {
    const meta = byCca2.get(code);
    if (!meta) return null;
    const currencyCode = Object.keys(meta.currencies ?? {})[0] ?? null;
    if (!currencyCode) return null;
    let dialCode;
    try {
      dialCode = getCountryCallingCode(code);
    } catch {
      return null;
    }
    return {
      code,
      name: meta.name.common,
      flag: meta.flag,
      dialCode: `+${dialCode}`,
      currency: currencyCode,
    };
  })
  .filter((r) => r !== null)
  .sort((a, b) => a.name.localeCompare(b.name));

const header = `// GENERATED by scripts/generate-country-data.mjs — do not hand-edit.
// Re-run \`node scripts/generate-country-data.mjs\` to refresh (requires
// world-countries as a devDependency; not needed at runtime).
export type CountryInfo = {
  code: string;
  name: string;
  flag: string;
  dialCode: string;
  currency: string;
};

export const COUNTRIES: CountryInfo[] = ${JSON.stringify(rows, null, 2)};
`;

writeFileSync(new URL("../lib/country-data.ts", import.meta.url), header);
console.log(`Wrote ${rows.length} countries to lib/country-data.ts`);
